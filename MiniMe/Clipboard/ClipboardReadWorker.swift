import AppKit
import ImageIO
import UniformTypeIdentifiers

struct ClipboardReadRequest: Codable {
    let pasteboardName: String
    let afterChangeCount: Int
    let captureImagesAndFiles: Bool
    let ignoreConcealed: Bool
}

struct ClipboardReadResponse: Codable {
    let changeCount: Int
    var entry: ClipboardEntry?
    var imageData: Data?
    var thumbnailData: Data?
    var fileBookmarks: [Data]?
}

protocol ClipboardReading: Sendable {
    @MainActor func read(_ request: ClipboardReadRequest) async -> ClipboardReadResponse?
}

/// A separate executable owns pasteboard reads and image conversion. Its sandbox
/// inherits the app's access, and it never initializes SwiftUI or hotkeys.
enum ClipboardReadWorker {
    static let argument = "MINIME_CLIPBOARD_WORKER"
    static let maxImageBytes = 25 * 1024 * 1024
    // Keep 6K and 8K screen captures within the limit.
    static let maxImagePixels = 40_000_000
    static let maxTextBytes = 4 * 1024 * 1024
    @MainActor private static var retireAfterResponse = false

    static func acceptsImageDimensions(width: Int, height: Int) -> Bool {
        width > 0 && height > 0 && width <= maxImagePixels / height
    }

    @MainActor
    static func runIfRequested() -> Bool {
        guard CommandLine.arguments.contains(argument) else { return false }
        while let line = readLine() {
            autoreleasepool {
                guard let data = line.data(using: .utf8),
                      let request = try? JSONDecoder().decode(ClipboardReadRequest.self, from: data),
                      let response = try? JSONEncoder().encode(read(request)) else { return }
                FileHandle.standardOutput.write(response)
                FileHandle.standardOutput.write(Data([10]))
            }
            // A thumbnail provider that ignored cancellation must not leave
            // suspended tasks accumulating in a long-running helper.
            if retireAfterResponse { return true }
        }
        return true
    }

    @MainActor
    private static func read(_ request: ClipboardReadRequest) -> ClipboardReadResponse {
        let board = NSPasteboard(name: .init(request.pasteboardName))
        let count = board.changeCount
        var response = ClipboardReadResponse(changeCount: count)
        guard count != request.afterChangeCount else { return response }
        let sensitive = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                         "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }
        guard !(request.ignoreConcealed && (board.types ?? []).contains(where: sensitive.contains)) else {
            return response
        }

        let app = NSWorkspace.shared.frontmostApplication
        let content: ClipboardContent
        if request.captureImagesAndFiles,
           let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            content = .files(paths: urls.map(\.path))
            // Transfer the pasteboard's temporary file access back to the app.
            // Paths alone would leave the parent without the helper's grant.
            response.fileBookmarks = urls.compactMap {
                try? $0.bookmarkData(options: [], includingResourceValuesForKeys: nil, relativeTo: nil)
            }
            // Keep the pasteboard's file access grant in this process while QuickLook reads.
            var finished = false
            let thumbnail = Task { @MainActor in
                response.thumbnailData = await ClipboardThumbnailer.fileThumbnailData(for: urls[0])
                finished = true
            }
            let deadline = Date().addingTimeInterval(1)
            while !finished && Date() < deadline {
                RunLoop.main.run(until: Date().addingTimeInterval(0.01))
            }
            thumbnail.cancel()
            retireAfterResponse = !finished
        } else if request.captureImagesAndFiles,
                  let type = board.availableType(from: [.png, .tiff] + NSImage.imageTypes.map { .init($0) }) {
            guard let data = board.data(forType: type), data.count <= maxImageBytes,
                  let image = prepareImage(data) else { return response }
            response.imageData = image.png
            response.thumbnailData = image.thumbnail
            content = .image(fileName: "\(UUID().uuidString).png",
                             pixelWidth: image.width, pixelHeight: image.height)
        } else {
            guard let string = board.string(forType: .string),
                  string.utf8.count <= maxTextBytes,
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return response }
            content = .text(string)
        }

        // A provider can finish after another app has replaced the clipboard.
        guard board.changeCount == count else {
            return ClipboardReadResponse(changeCount: count)
        }
        response.entry = ClipboardEntry(content: content, sourceAppName: app?.localizedName,
                                        sourceAppBundleID: app?.bundleIdentifier)
        return response
    }

    /// Inspect dimensions without decoding the bitmap. Keep a PNG's original
    /// bytes, and use ImageIO for TIFF conversion rather than expanding NSImage.
    static func prepareImage(_ data: Data) -> (png: Data, thumbnail: Data?, width: Int, height: Int)? {
        guard data.count <= maxImageBytes,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              acceptsImageDimensions(width: width, height: height) else { return nil }
        let png: Data
        if CGImageSourceGetType(source) == UTType.png.identifier as CFString {
            png = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
                  let encoded = encodePNG(image), encoded.count <= maxImageBytes else { return nil }
            png = encoded
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 240
        ]
        let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
        return (png, thumb.flatMap(encodePNG), width, height)
    }

    private static func encodePNG(_ image: CGImage) -> Data? {
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }
}

/// All pipe operations are confined to one queue. The UI only awaits results.
/// A separate deadline kills a stuck worker, including a synchronous IPC read.
final class ClipboardReadService: ClipboardReading, @unchecked Sendable {
    private let queue = DispatchQueue(label: "com.minime.clipboard-reader", qos: .utility)
    private var process: Process?
    private var input: FileHandle?
    private var output: FileHandle?
    private var buffered = Data()
    private let timeout: TimeInterval

    init(timeout: TimeInterval = 5) { self.timeout = timeout }

    deinit {
        if let process, process.isRunning { process.terminate() }
    }

    func read(_ request: ClipboardReadRequest) async -> ClipboardReadResponse? {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume(returning: self.readBlocking(request)) }
        }
    }

    private func readBlocking(_ request: ClipboardReadRequest) -> ClipboardReadResponse? {
        do {
            if process?.isRunning != true {
                let child = Process()
                child.executableURL = Bundle.main.bundleURL.pathExtension == "app"
                    ? Bundle.main.bundleURL.appendingPathComponent("Contents/MacOS/MiniMeClipboardWorker")
                    : Bundle.main.executableURL
                child.arguments = [ClipboardReadWorker.argument]
                // A test-host injection must not turn the worker into another test run.
                child.environment = ProcessInfo.processInfo.environment.filter {
                    !$0.key.hasPrefix("XCTest") && !$0.key.hasPrefix("XCInject")
                        && $0.key != "DYLD_INSERT_LIBRARIES"
                }
                let incoming = Pipe(), outgoing = Pipe()
                child.standardInput = incoming
                child.standardOutput = outgoing
                child.standardError = FileHandle.nullDevice
                try child.run()
                process = child
                input = incoming.fileHandleForWriting
                // A helper may exit between isRunning and write. Convert a
                // broken pipe into a recoverable error instead of SIGPIPE.
                _ = fcntl(incoming.fileHandleForWriting.fileDescriptor, F_SETNOSIGPIPE, 1)
                output = outgoing.fileHandleForReading
                buffered.removeAll()
            }
            guard let child = process, let input, let output else { return nil }
            let deadline = DispatchWorkItem {
                if child.isRunning { kill(child.processIdentifier, SIGKILL) }
            }
            DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + timeout, execute: deadline)
            defer { deadline.cancel() }
            var data = try JSONEncoder().encode(request)
            data.append(10)
            try input.write(contentsOf: data)
            // Exactly one response is outstanding. JSONEncoder escapes newlines
            // inside strings, so the final byte marks the end of the response.
            // Avoid rescanning an entire large image payload for every chunk.
            while buffered.last != 10 {
                let chunk = output.availableData
                guard !chunk.isEmpty else { throw CocoaError(.fileReadUnknown) }
                buffered.append(chunk)
            }
            let line = buffered.dropLast()
            let response = try JSONDecoder().decode(ClipboardReadResponse.self, from: line)
            buffered.removeAll()
            return response
        } catch {
            if let process {
                if process.isRunning { kill(process.processIdentifier, SIGKILL) }
                process.waitUntilExit()
            }
            process = nil
            input = nil
            output = nil
            buffered.removeAll()
            return nil
        }
    }
}
